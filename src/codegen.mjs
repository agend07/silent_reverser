import {
  computeStructLayout,
  formatHex,
  parseHex,
  pointerSize,
  validIdentifier,
  validRelativePath,
} from './config.mjs';

/**
 * Validates the entire state and returns computed layouts for all structs in topological order.
 */
export function validateAndLayoutState(state, config) {
  const knownEnums = new Map();
  for (const en of state.enums || []) {
    if (!validIdentifier(en.name)) throw new Error(`Invalid enum name: ${en.name}`);
    if (knownEnums.has(en.name)) throw new Error(`Duplicate enum name: ${en.name}`);
    const seenValues = new Set();
    for (const val of en.values || []) {
      if (!validIdentifier(val.name)) throw new Error(`Invalid enum member name: ${en.name}::${val.name}`);
      if (seenValues.has(val.name)) throw new Error(`Duplicate enum member: ${en.name}::${val.name}`);
      seenValues.add(val.name);
      parseHex(val.value);
    }
    knownEnums.set(en.name, en);
  }

  // Topological sort of structs by inheritance and by-value references
  const structMap = new Map();
  for (const st of state.structs || []) {
    if (!validIdentifier(st.name)) throw new Error(`Invalid struct name: ${st.name}`);
    if (structMap.has(st.name)) throw new Error(`Duplicate struct name: ${st.name}`);
    if (st.vtable) parseHex(st.vtable);
    for (const vm of st.vtableMethods || []) {
      if (!validIdentifier(vm.name)) throw new Error(`Invalid vtable method name: ${st.name}::${vm.name}`);
      if (!Number.isInteger(vm.index) || vm.index < 0) throw new Error(`Invalid vtable index for ${st.name}::${vm.name}`);
      if (vm.address) parseHex(vm.address);
    }
    const seenFields = new Set();
    for (const f of st.fields || []) {
      if (!validIdentifier(f.name)) throw new Error(`Invalid field name: ${st.name}::${f.name}`);
      if (/^pad_[0-9a-fA-F]+$/i.test(f.name)) {
        throw new Error(`Do not pass manual padding field "${st.name}::${f.name}". Padding is calculated automatically.`);
      }
      if (seenFields.has(f.name)) throw new Error(`Duplicate field name: ${st.name}::${f.name}`);
      seenFields.add(f.name);
      parseHex(f.offset);
    }
    structMap.set(st.name, st);
  }

  const knownStructSizes = new Map();
  const layouts = [];
  const visiting = new Set();
  const visited = new Set();

  function visitStruct(name) {
    if (visited.has(name)) return;
    if (visiting.has(name)) throw new Error(`Circular struct dependency involving "${name}".`);
    visiting.add(name);
    const st = structMap.get(name);
    if (st.inherits) {
      if (!structMap.has(st.inherits)) {
        throw new Error(`Struct "${st.name}" inherits from unknown struct "${st.inherits}".`);
      }
      visitStruct(st.inherits);
    }
    for (const f of st.fields || []) {
      const clean = f.type.trim().replace(/\s*\[.*\]$/, '').trim();
      if (!clean.endsWith('*') && structMap.has(clean)) {
        visitStruct(clean);
      }
    }
    const layout = computeStructLayout(st, config.arch, knownStructSizes, knownEnums);
    knownStructSizes.set(name, layout.totalSize);
    layouts.push(layout);
    visiting.delete(name);
    visited.add(name);
  }

  for (const name of structMap.keys()) {
    visitStruct(name);
  }

  // Validate globals
  const seenGlobals = new Set();
  for (const g of state.globals || []) {
    if (!validIdentifier(g.name)) throw new Error(`Invalid global name: ${g.name}`);
    if (seenGlobals.has(g.name)) throw new Error(`Duplicate global name: ${g.name}`);
    seenGlobals.add(g.name);
    parseHex(g.address);
  }

  // Validate functions
  const seenFuncAddresses = new Set();
  for (const fn of state.functions || []) {
    if (!validIdentifier(fn.name)) throw new Error(`Invalid function name: ${fn.name}`);
    const addrNum = parseHex(fn.address);
    const addrKey = formatHex(addrNum, 8);
    if (seenFuncAddresses.has(addrKey)) throw new Error(`Duplicate function address: ${addrKey}`);
    seenFuncAddresses.add(addrKey);
    if (fn.decompiledFile) {
      if (!validRelativePath(fn.decompiledFile)) {
        throw new Error(`Invalid decompiledFile path for ${fn.name}: ${fn.decompiledFile}`);
      }
    }
  }

  return { layouts, knownEnums, knownStructSizes };
}

/**
 * Generates deterministic `/sdk/SDK.h` content with explicit padding and static_asserts.
 */
export function generateSdkHeader(state, config) {
  const { layouts } = validateAndLayoutState(state, config);
  const ptrBits = pointerSize(config.arch) * 8;
  const lines = [
    '#pragma once',
    config.databasePath?.startsWith('.pi/')
      ? `// Auto-generated by pi-reverser (Single Source of Truth: ${config.databasePath})` // legacy wording, keeps Pi-written artifacts "fresh"
      : `// Auto-generated by reverser (Single Source of Truth: ${config.databasePath ?? '.reverser/reverser.json'})`,
    `// Target: ${config.target} (${config.arch}, ${ptrBits}-bit, ImageBase: ${config.imageBase})`,
    ...(config.sha256 ? [`// SHA-256: ${config.sha256}`] : []),
    '',
    '#include <cstdint>',
    '#include <cstddef>',
    '',
  ];

  if (config.namespace) {
    lines.push(`namespace ${config.namespace} {`, '');
  }

  // Built-in math primitives if not defined by user structs
  const userStructNames = new Set((state.structs || []).map(s => s.name));
  const mathTypes = [
    ['Vector2', 'struct Vector2 { float x, y; };'],
    ['Vector3', 'struct Vector3 { float x, y, z; };'],
    ['Vector4', 'struct Vector4 { float x, y, z, w; };'],
    ['Matrix3x4', 'struct Matrix3x4 { float m[3][4]; };'],
    ['Matrix4x4', 'struct Matrix4x4 { float m[4][4]; };'],
  ];
  const neededMath = mathTypes.filter(([name]) => !userStructNames.has(name));
  if (neededMath.length) {
    lines.push('// Math primitives');
    for (const [, decl] of neededMath) lines.push(decl);
    lines.push('');
  }

  // Forward declarations of structs
  if (layouts.length) {
    lines.push('// Forward declarations');
    for (const layout of layouts) {
      lines.push(`struct ${layout.name};`);
    }
    lines.push('');
  }

  // Enums
  if (state.enums?.length) {
    lines.push('// Enums');
    for (const en of state.enums) {
      const underlying = en.underlyingType || 'uint32_t';
      if (en.comment) lines.push(`// ${en.comment}`);
      lines.push(`enum class ${en.name} : ${underlying} {`);
      for (const val of en.values || []) {
        const hexVal = formatHex(parseHex(val.value), 1);
        const comment = val.comment ? ` // ${val.comment}` : '';
        lines.push(`    ${val.name} = ${hexVal},${comment}`);
      }
      lines.push('};', '');
    }
  }

  // Structs
  for (const layout of layouts) {
    const headerMeta = [];
    if (layout.vtable) headerMeta.push(`vtable: ${formatHex(parseHex(layout.vtable), 8)}`);
    headerMeta.push(`size: ${layout.totalSizeHex}`);
    if (layout.comment) lines.push(`// ${layout.comment}`);
    lines.push(`// [${headerMeta.join(' | ')}]`);
    const inheritClause = layout.inherits ? ` : public ${layout.inherits}` : '';
    lines.push(`struct ${layout.name}${inheritClause} {`);

    if (layout.vtableMethods.length) {
      lines.push('    // VTable methods:');
      for (const vm of layout.vtableMethods) {
        const slotOffset = formatHex(vm.index * pointerSize(config.arch), 2);
        const addrPart = vm.address ? ` @ ${formatHex(parseHex(vm.address), 8)}` : '';
        const sigPart = vm.signature ? ` -> ${vm.signature}` : '';
        const cmtPart = vm.comment ? ` (${vm.comment})` : '';
        lines.push(`    // [${vm.index} | +${slotOffset}] ${vm.name}${addrPart}${sigPart}${cmtPart}`);
      }
    }

    for (const item of layout.items) {
      const paddedDecl = `${item.decl};`.padEnd(40, ' ');
      if (item.kind === 'pad') {
        lines.push(`    ${paddedDecl} // ${item.offsetHex} - ${item.endOffsetHex}`);
      } else {
        const tags = [];
        if (item.confidence === 'guessed') tags.push('Type unconfirmed (guessed)');
        else if (item.confidence === 'probable') tags.push('Type probable');
        if (item.comment) tags.push(item.comment);
        const suffix = tags.length ? ` | ${tags.join(' - ')}` : '';
        lines.push(`    ${paddedDecl} // ${item.offsetHex} (size: ${formatHex(item.resolvedSize, 1)})${suffix}`);
      }
    }
    lines.push('};');

    // Emit static_asserts for confirmed/all fields when not using inheritance (standard layout)
    for (const item of layout.items) {
      if (item.kind === 'field') {
        lines.push(`static_assert(offsetof(${layout.name}, ${item.name}) == ${item.offsetHex}, "Offset mismatch for ${layout.name}::${item.name}");`);
      }
    }
    if (layout.totalSize > 0) {
      lines.push(`static_assert(sizeof(${layout.name}) == ${layout.totalSizeHex}, "Size mismatch for ${layout.name}");`);
    }
    lines.push('');
  }

  // Globals
  if (state.globals?.length) {
    lines.push('// Global addresses & pointers');
    lines.push('namespace Offsets {');
    for (const g of state.globals) {
      const addrHex = formatHex(parseHex(g.address), 8);
      const extras = [`type: ${g.type}`];
      if (g.signature) extras.push(`sig: "${g.signature}"`);
      if (g.comment) extras.push(g.comment);
      lines.push(`    constexpr uintptr_t ${g.name} = ${addrHex}; // ${extras.join(' | ')}`);
    }
    lines.push('}', '');
  }

  // Functions
  if (state.functions?.length) {
    lines.push('// Known functions');
    lines.push('namespace Functions {');
    const sortedFns = [...state.functions].sort((a, b) => parseHex(a.address) - parseHex(b.address));
    for (const fn of sortedFns) {
      const addrHex = formatHex(parseHex(fn.address), 8);
      const conv = fn.callingConvention ? `${fn.callingConvention} ` : '';
      const sig = fn.signature || `void(${conv}*)()`;
      const extras = [sig];
      if (fn.decompiledFile) extras.push(`file: ${fn.decompiledFile}`);
      if (fn.comment) extras.push(fn.comment);
      lines.push(`    constexpr uintptr_t ${fn.name} = ${addrHex}; // ${extras.join(' | ')}`);
    }
    lines.push('}', '');
  }

  if (config.namespace) {
    lines.push(`} // namespace ${config.namespace}`, '');
  }

  return lines.join('\n');
}

/**
 * Generates deterministic `/sdk/offsets.json` content.
 */
export function generateOffsetsJson(state, config) {
  const { layouts } = validateAndLayoutState(state, config);
  const payload = {
    target: config.target,
    binaryPath: config.binaryPath || undefined,
    sha256: config.sha256 || undefined,
    arch: config.arch,
    imageBase: formatHex(parseHex(config.imageBase), 8),
    globals: Object.fromEntries(
      [...(state.globals || [])]
        .sort((a, b) => parseHex(a.address) - parseHex(b.address))
        .map(g => [
          g.name,
          {
            address: formatHex(parseHex(g.address), 8),
            type: g.type,
            ...(g.signature ? { signature: g.signature } : {}),
            ...(g.pointerChain?.length ? { pointerChain: g.pointerChain } : {}),
            ...(g.comment ? { comment: g.comment } : {}),
          },
        ])
    ),
    vtables: Object.fromEntries(
      layouts
        .filter(l => l.vtable || l.vtableMethods.length)
        .map(l => [
          l.name,
          {
            ...(l.vtable ? { address: formatHex(parseHex(l.vtable), 8) } : {}),
            methods: l.vtableMethods.map(vm => ({
              index: vm.index,
              offset: formatHex(vm.index * pointerSize(config.arch), 2),
              name: vm.name,
              ...(vm.address ? { address: formatHex(parseHex(vm.address), 8) } : {}),
              ...(vm.signature ? { signature: vm.signature } : {}),
              ...(vm.comment ? { comment: vm.comment } : {}),
            })),
          },
        ])
    ),
    structs: Object.fromEntries(
      layouts.map(l => [
        l.name,
        {
          size: l.totalSizeHex,
          ...(l.inherits ? { inherits: l.inherits } : {}),
          fields: Object.fromEntries(
            l.items
              .filter(i => i.kind === 'field')
              .map(f => [
                f.name,
                {
                  offset: f.offsetHex,
                  size: formatHex(f.resolvedSize, 1),
                  type: f.type,
                  confidence: f.confidence || 'confirmed',
                  ...(f.comment ? { comment: f.comment } : {}),
                },
              ])
          ),
        },
      ])
    ),
    functions: Object.fromEntries(
      [...(state.functions || [])]
        .sort((a, b) => parseHex(a.address) - parseHex(b.address))
        .map(fn => [
          fn.name,
          {
            address: formatHex(parseHex(fn.address), 8),
            ...(fn.callingConvention ? { callingConvention: fn.callingConvention } : {}),
            ...(fn.signature ? { signature: fn.signature } : {}),
            ...(fn.decompiledFile ? { decompiledFile: fn.decompiledFile } : {}),
            ...(fn.confidence ? { confidence: fn.confidence } : {}),
            ...(fn.comment ? { comment: fn.comment } : {}),
          },
        ])
    ),
  };
  return JSON.stringify(payload, null, 2) + '\n';
}
